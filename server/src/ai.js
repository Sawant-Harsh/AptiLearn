export function parseJsonArray(text) {
  const cleaned = text.replace(/```json|```/g, '');
  const a = cleaned.indexOf('[');
  const b = cleaned.lastIndexOf(']');
  if (a < 0 || b < 0) throw new HttpError(502, 'The AI did not return valid JSON. Please try again.');
  return JSON.parse(cleaned.slice(a, b + 1));
}

export function validateGenerated(items, { courseId, topic, difficulty }) {
  const out = [];
  for (const it of items) {
    const options = Array.isArray(it.options) ? it.options.map((o) => String(o).trim()) : [];
    const answer = Number.isInteger(it.answer) ? it.answer : parseInt(it.answer, 10);
    if (!it.text || options.length !== 4 || new Set(options.map((o) => o.toLowerCase())).size !== 4 || !(answer >= 0 && answer <= 3)) continue;
    out.push({ courseId, topic, difficulty, text: String(it.text).trim(), code: it.code ? String(it.code) : undefined, options, answer, explanation: String(it.explanation || '').trim() || 'Generated by AI.' });
  }
  return out;
}

export async function generateQuestions({ course, topic, difficulty, count }) {
  const text = await claude({
    maxTokens: 4000,
    system: 'You write accurate multiple-choice questions for a university-level learning platform. Respond with ONLY a JSON array, no prose and no markdown fences.',
    messages: [{
      role: 'user',
      content: `Write ${count} distinct ${difficulty}-difficulty multiple-choice questions for the course "${course.name}", topic "${topic}".
Each item must be an object: {"text": string, "code": string (optional code snippet, omit if none), "options": [exactly 4 different strings], "answer": index 0-3 of the single correct option, "explanation": one or two sentences}.
Make sure exactly one option is correct, distractors are plausible, and the answer index is correct. Vary the position of the correct answer.`,
    }],
  });
  return validateGenerated(parseJsonArray(text), { courseId: course.id, topic, difficulty });
}

/** Resolve a real, embeddable YouTube video for a lesson (YouTube Data API v3), cached by caller. */
export async function searchYoutube(query) {
  const key = process.env.YOUTUBE_API_KEY;
  if (!key) return null;
  const url = `https://www.googleapis.com/youtube/v3/search?part=snippet&type=video&videoEmbeddable=true&videoSyndicated=true&safeSearch=strict&maxResults=1&relevanceLanguage=en&q=${encodeURIComponent(query)}&key=${key}`;
  const res = await fetch(url);
  const data = await res.json().catch(() => ({}));
  if (!res.ok) throw new HttpError(502, data?.error?.message || 'YouTube search failed');
  const item = data.items?.[0];
  return item ? { videoId: item.id.videoId, title: item.snippet.title, channel: item.snippet.channelTitle } : null;
}

